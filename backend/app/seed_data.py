def seed_questions(db: Session) -> None:
    existing_count = db.query(models.Question).count()
    if existing_count > 0:
        return
    for text, category in INITIAL_QUESTIONS:
        db.add(models.Question(text=text, category=category))
    db.commit()


def run_all_seeds(db: Session) -> None:
    seed_questions(db)
    crud.seed_achievements(db)
