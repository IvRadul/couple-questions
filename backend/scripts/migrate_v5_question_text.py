def run() -> None:
    db = SessionLocal()
    updated = 0
    try:
        for old_text, new_text in TEXT_MIGRATIONS:
            question = db.query(models.Question).filter(models.Question.text == old_text).first()
            if question is None:
                continue
            question.text = new_text
            updated += 1
        db.commit()
    finally:
        db.close()
    print(f"Обновлено вопросов: {updated} из {len(TEXT_MIGRATIONS)} возможных")


if __name__ == "__main__":
    run()
